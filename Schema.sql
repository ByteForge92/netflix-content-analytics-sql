CREATE TABLLE netflix (
	show_id varchar(7),
	type varchar(7),
	title varchar(105),
	director varchar(210),
	cast varchar(775),
	country varchar(123),
	date_added varchar(19),
	release_year varchar(12),
	rating varchar(8),
	duration varchar(10),
	listed_in varchar(79),
	description varchar(250)
);

USE netflix;
